// 동굴 하나의 방 목록 (마지막에 새벽의 방, 단계는 동굴 차례에 따라)
export function roomsOf(d) {
  const i = DUNGEONS.indexOf(d);
  return [...d.rooms.map(([t, lv]) => ({ t, lv })), { t: 'dawn', lv: i < 3 ? 1 : i < 6 ? 2 : 3 }];
}

